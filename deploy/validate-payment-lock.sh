#!/bin/sh
# Проверка переменных блокировки по оплате ПЕРЕД тем, как штатный энтрипойнт nginx подставит их в
# конфиг — и заодно единственная строка в логе, по которой видно, что сервер вообще о ней думает.
#
# ⚠ envsubst — тупая текстовая подстановка. Значения уезжают ВНУТРЬ JSON-строки
# `return 200 '{"softFrom":"${…}"}'`, поэтому кавычка, обратный слэш или точка с запятой в значении
# ломают либо JSON, либо сам конфиг nginx. Формат даты жёсткий (`YYYY-MM-DD`), рубильник — из
# короткого списка слов; всё остальное роняет контейнер.
#
# ⚠ Почему роняет, а не «игнорируем и работаем». Приложение разбирает настройки проверяюще и на
# мусор отвечает «блокировки нет» — то есть опечатка в `.env` дала бы ТИХО неработающую блокировку,
# и владелец узнал бы об этом, только не дождавшись реакции клиента. Пустые значения при этом
# полностью законны: свежий контейнер без настроек работает как обычно.
#
# Имя файла с `06-` — после проверки доменов и раньше штатного `20-envsubst-on-templates.sh`.
set -eu

soft="${PAYMENT_LOCK_SOFT_FROM:-}"
hard="${PAYMENT_LOCK_HARD_FROM:-}"
off="${PAYMENT_LOCK_OFF:-}"

# Календарный день: ровно четыре цифры, дефис, две, дефис, две. Ни пробелов, ни кавычек, ни
# «сегодня». Настоящую дату (не «2026-02-31») проверяет уже приложение.
check_day() {
  name="$1"
  value="$2"
  [ -z "$value" ] && return 0
  case "$value" in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) return 0 ;;
    *) echo "$name: «$value» — нужен день в формате YYYY-MM-DD или пусто" >&2; exit 1 ;;
  esac
}

check_day PAYMENT_LOCK_SOFT_FROM "$soft"
check_day PAYMENT_LOCK_HARD_FROM "$hard"

case "$off" in
  ''|0|1|true|false|yes|no|on|off) ;;
  *) echo "PAYMENT_LOCK_OFF: «$off» — допустимы 1/0, true/false, yes/no, on/off или пусто" >&2; exit 1 ;;
esac

# ⚠ Строка в логе обязательна. Блокировка — единственная настройка, чьё ОТСУТСТВИЕ выглядит ровно
# как исправная работа: не скажи сервер при старте, чего он ждёт, разбираться пришлось бы по
# поведению клиента.
case "$off" in
  1|true|yes|on) echo "[lock] блокировка снята рубильником PAYMENT_LOCK_OFF"; exit 0 ;;
esac
if [ -z "$soft" ] && [ -z "$hard" ]; then
  echo "[lock] блокировка не настроена — приложение работает как обычно"
else
  echo "[lock] напоминание с ${soft:-(не задано)}, полная блокировка с ${hard:-(не задана)}"
fi
