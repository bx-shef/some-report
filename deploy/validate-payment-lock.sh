#!/bin/sh
# Проверка переменных блокировки по оплате ПЕРЕД тем, как штатный энтрипойнт nginx подставит их в
# конфиг — и заодно единственная строка в логе, по которой видно, что сервер вообще о ней думает.
#
# ⚠ envsubst — тупая текстовая подстановка. Значения уезжают ВНУТРЬ JSON-строки
# `return 200 '{"softFrom":"${…}"}'`, поэтому кавычка, обратный слэш или точка с запятой в значении
# ломают либо JSON, либо сам конфиг nginx. Формат даты жёсткий (`YYYY-MM-DD`), рубильник — из
# короткого списка слов; всё остальное роняет контейнер.
#
# ⚠ Почему роняет, а не «игнорируем и работаем». Приложение разбирает настройки проверяюще и на
# мусор отвечает «блокировки нет» — то есть опечатка в `.env` дала бы ТИХО неработающую блокировку,
# и владелец узнал бы об этом, только не дождавшись реакции клиента. Пустые значения при этом
# полностью законны: свежий контейнер без настроек работает как обычно.
#
# Имя файла с `06-` — после проверки доменов и раньше штатного `20-envsubst-on-templates.sh`.
set -eu

soft="${PAYMENT_LOCK_SOFT_FROM:-}"
hard="${PAYMENT_LOCK_HARD_FROM:-}"
off="${PAYMENT_LOCK_OFF:-}"

# Календарный день: ровно четыре цифры, дефис, две, дефис, две — и СУЩЕСТВУЮЩИЙ день.
#
# ⚠ Одного формата мало, и это не педантизм. `2026-09-31` формат проходит, контейнер стартует и
# бодро пишет в лог «полная блокировка с 2026-09-31» — а приложение такую дату отбрасывает
# (`validDayKey` проверяет её round-trip'ом), и блокировка молча не включается. То есть ровно тот
# исход, ради предотвращения которого этот скрипт и роняет контейнер. Найдено проверкой PR #72.
# Число без ведущих нулей: в арифметике шелла `08` читается как восьмеричное и роняет выражение.
#
# ⚠ Именно так, а не `$((10#$n))`: запись с основанием — башизм, а в образе busybox-овский `sh`,
# где она обрывает проверку ошибкой разбора. Проверено запуском: под `dash` падали ВСЕ даты, и
# годные тоже.
no_zeros() {
  stripped="${1#"${1%%[!0]*}"}"
  echo "${stripped:-0}"
}

check_day() {
  name="$1"
  value="$2"
  [ -z "$value" ] && return 0
  case "$value" in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
    *) echo "$name: «$value» — нужен день в формате YYYY-MM-DD или пусто" >&2; exit 1 ;;
  esac

  # ⚠ Считаем календарь сами, а не через `date -d`: в образе busybox, и его `date` разбирает
  # несуществующие дни молча, докатывая их до следующего месяца, — то есть даёт ровно ту ошибку,
  # которую мы здесь ловим.
  year=$(no_zeros "${value%%-*}")
  rest=${value#*-}
  month=$(no_zeros "${rest%%-*}")
  day=$(no_zeros "${rest#*-}")

  case "$month" in
    1|3|5|7|8|10|12) last=31 ;;
    4|6|9|11) last=30 ;;
    2) if [ $((year % 4)) -eq 0 ] && { [ $((year % 100)) -ne 0 ] || [ $((year % 400)) -eq 0 ]; }
       then last=29; else last=28; fi ;;
    *) echo "$name: «$value» — месяца $month не существует" >&2; exit 1 ;;
  esac
  if [ "$day" -lt 1 ] || [ "$day" -gt "$last" ]; then
    echo "$name: «$value» — такого дня нет: в этом месяце их $last" >&2; exit 1
  fi
}

check_day PAYMENT_LOCK_SOFT_FROM "$soft"
check_day PAYMENT_LOCK_HARD_FROM "$hard"

case "$off" in
  ''|0|1|true|false|yes|no|on|off) ;;
  *) echo "PAYMENT_LOCK_OFF: «$off» — допустимы 1/0, true/false, yes/no, on/off или пусто" >&2; exit 1 ;;
esac

# ⚠ Строка в логе обязательна. Блокировка — единственная настройка, чьё ОТСУТСТВИЕ выглядит ровно
# как исправная работа: не скажи сервер при старте, чего он ждёт, разбираться пришлось бы по
# поведению клиента.
case "$off" in
  1|true|yes|on) echo "[lock] блокировка снята рубильником PAYMENT_LOCK_OFF"; exit 0 ;;
esac
if [ -z "$soft" ] && [ -z "$hard" ]; then
  echo "[lock] блокировка не настроена — приложение работает как обычно"
else
  # ⚠ Сегодняшний день печатается рядом НАМЕРЕННО. Опечатку в годе (2026 вместо 2027) не отличить
  # от верной даты никакой проверкой — а рядом с сегодняшним числом она бросается в глаза тому, кто
  # запускает контейнер, в тот единственный момент, когда это ещё можно поправить дёшево.
  echo "[lock] сегодня $(date +%F): напоминание с ${soft:-(не задано)}, полная блокировка с ${hard:-(не задана)}"
fi
