/**
 * `ru-RU` разделяет разряды НЕРАЗРЫВНЫМ пробелом (U+00A0), а перед знаком процента может
 * поставить узкий неразрывный (U+202F). Приводим их к обычному пробелу, чтобы ожидания в тестах
 * читались глазами.
 *
 * ⚠ Escape-последовательностями намеренно: набранные буквально, эти символы неотличимы от
 * обычного пробела при чтении диффа — и тест краснеет «без причины».
 */
export function nbsp(value: string): string {
  return value.replace(/[\u00A0\u202F]/g, ' ')
}
