/**
 * Проволока до портала: что переживёт дорогу до него, а что нет.
 *
 * ⛔ Заведено по боевому инциденту 2026-09-14. Клик по причине проигрыша открывал слайдер с
 * верным заголовком и красной плашкой вместо списка:
 *
 * > Failed to execute 'structuredClone' on 'Window': [object Object] could not be cloned.
 *
 * Фрейм разговаривает с порталом через `postMessage`, а браузер клонирует нагрузку СТРУКТУРНО.
 * Структурное клонирование не умеет копировать `Proxy` — то есть ровно то, чем является
 * реактивность Vue. Значение, дошедшее до запроса прямо из `ref`, роняет запрос целиком.
 *
 * ⚠ Все стенды были ЩЕДРЕЕ настоящего SDK: они брали объект как есть и потому оставались
 * зелёными при выборке, которая на боевом портале не работала ни разу. Ровно тот же класс
 * дефекта, что стоил отчёту 229 фамилий (`docs/PORTAL.md`), — и лечится он так же: стенд обязан
 * вести себя не мягче реальности.
 */

/**
 * Параметры так, как их получит портал.
 *
 * Стенды зовут её на КАЖДОМ запросе: `structuredClone` здесь не украшение, а та самая проверка,
 * которую делает браузер. Отказ переводится в понятный текст — иначе разбираться пришлось бы по
 * `DataCloneError` без единого указания, какое поле условия виновато.
 */
export function asPortalWire<T>(params: T): T {
  try {
    return structuredClone(params)
  } catch {
    throw new Error(
      `Параметры запроса не переживают postMessage: в них попал Proxy (реактивность Vue) или другое неклонируемое значение. `
      + `На боевом портале это «Failed to execute 'structuredClone' on 'Window'» вместо списка. `
      + `Лечится вызовом plainParams() на границе с SDK — см. app/utils/b24Params.ts. `
      + `Условие: ${safePreview(params)}`
    )
  }
}

/** Показать негодное условие, не споткнувшись о него второй раз. */
function safePreview(params: unknown): string {
  try {
    return JSON.stringify(params)?.slice(0, 300) ?? String(params)
  } catch {
    return String(params)
  }
}
