import {
  LOCK_RELEASE_SECONDS,
  lockAppliesTo,
  lockStageFor,
  parseLockSchedule,
  type PaymentLockStage
} from '~/utils/paymentLock'

/**
 * Блокировка приложения при неподписанных актах — реактивная обвязка над чистым ядром
 * (`app/utils/paymentLock.ts`). Здесь ровно три вещи, которых у чистых функций быть не может:
 * чтение настроек с сервера, часы и обратный отсчёт.
 *
 * ⛔ Страница НЕ МОНТИРУЕТСЯ, пока решение не принято (`resolved`), и это не перестраховка, а
 * исправление двух настоящих дефектов, найденных проверками PR #72.
 *
 * Экран встаёт на место страницы, но решение приходит с сервера, то есть асинхронно, — а дочерний
 * `onMounted` выполняется РАНЬШЕ родительского. Пока страница монтировалась сразу, за эти доли
 * секунды успевало произойти два необратимых действия. Первое: отчёт начинал читать CRM, то есть
 * при ЖЁСТКОЙ блокировке приложение всё равно шло в портал клиента — ровно вопреки тому, что
 * обещает экран. Второе, хуже: главная приложения читала ОДНОРАЗОВОЕ условие детализации из
 * `user.option` и СТИРАЛА его; после двадцати секунд отсчёта страница монтировалась заново и
 * получала «условие устарело» на совершенно исправном запросе. То есть при включённом напоминании
 * каждый клик по числу открывал бы «Список не открылся».
 *
 * ⚠ Ожидание НЕ ломает пререндер, и это ключ ко всей конструкции: `resolved` считается из пути
 * СИНХРОННО, поэтому публичная страница и установщик запекаются с содержимым как прежде, а
 * страницы приложения — пустыми. Пустыми они и отрисовываются на первом клиентском кадре, то есть
 * гидратация СОВПАДАЕТ. Отчёты и так рисуются только на клиенте (данные берутся из портала), так
 * что терять нечего.
 *
 * ⚠ Первая редакция принимала решение в клиентском плагине, до монтирования. Так делать нельзя:
 * пререндер идёт без клиентского плагина, и в заблокированном приложении первый кадр расходился с
 * запечённой разметкой. Vue на расхождении не перерисовывает узел, а ЛАТАЕТ его — проверено на
 * собранной статике: у корня остались классы запечённой заглушки, разметка экрана не применилась
 * вовсе, и экран выглядел сломанным.
 *
 * ⚠ Вторая редакция заставляла КАЖДУЮ страницу ждать разрешения в своём `onMounted`. Работало, но
 * ценой: тридцать чужих тестов страниц начинали висеть, потому что о блокировке теперь обязана
 * знать каждая страница. Знание о блокировке живёт в одном месте — здесь и в `app.vue`.
 */

/** Сколько ждём ответа от сервера с настройками, прежде чем решить, что их нет. */
const CONFIG_TIMEOUT_MS = 1200

/** Шаг отсчёта. Полсекунды, а не секунда: подпись меняется вовремя, даже если такт чуть уплыл. */
const TICK_MS = 500

/**
 * Стадия блокировки, посчитанная по ответу сервера.
 *
 * ⚠ Через `useState`, а не через модульную переменную: модульная пережила бы переход между
 * страницами, но не пережила бы пререндер — на сервере состояние модуля общее для всех собираемых
 * страниц, и одна заблокированная запекла бы блокировку во все остальные.
 */
export const usePaymentLockStage = () => useState<PaymentLockStage>('payment-lock-stage', () => 'none')

/** День, с которого приложение перестанет открываться, — если он задан на сервере. */
export const usePaymentLockHardFrom = () => useState<string | undefined>('payment-lock-hard-from', () => undefined)

/**
 * Решение принято: сервер ответил (или не ответил — неважно), стадия известна.
 *
 * ⚠ До этого момента страница не монтируется вовсе, поэтому значение читает `app.vue`, а не
 * страницы: знание о блокировке живёт в одном месте.
 */
export const usePaymentLockResolved = () => useState('payment-lock-resolved', () => false)

/** Мягкая блокировка отсидена: отсчёт закончился и больше никого не держит. */
export const usePaymentLockReleased = () => useState('payment-lock-released', () => false)

/**
 * Настройки блокировки с сервера. Пустой объект — «блокировки нет», и ровно так же трактуется
 * любой отказ.
 *
 * ⛔ Ошибка обязана уводить В СТОРОНУ РАБОТАЮЩЕГО отчёта. Сервер не ответил, ответил мусором,
 * ответил 404 (так ведёт себя дев-сервер — файла там нет вовсе) — приложение работает. Запереть
 * клиента из-за своей же неполадки хуже, чем не показать напоминание: напоминание вернётся
 * завтра, а потерянный рабочий день не вернётся.
 */
export async function readLockSchedule() {
  try {
    return parseLockSchedule(await $fetch('/payment-lock.json', { timeout: CONFIG_TIMEOUT_MS, retry: 0 }))
  } catch {
    return {}
  }
}

/**
 * Спросить сервер и решить, блокируем ли. Зовётся ОДИН раз — из `app/app.vue`.
 *
 * @param pathname путь открытой страницы — `/install` и публичная `/` блокировкой не затрагиваются
 * @param lockParam значение `?lock` ИЗ РОУТЕРА (`route.query.lock`) — обход для показа экрана до
 *   наступления даты. ⚠ Именно из роутера: `window.location.search` к этому моменту уже пуст,
 *   роутер переписывает адрес на начальной навигации. Проверено на собранной статике — обход молча
 *   не срабатывал.
 */
export async function resolvePaymentLock(pathname: string, lockParam: unknown): Promise<void> {
  const resolved = usePaymentLockResolved()
  // Решаем ДО запроса: на страницах вне блокировки ответ сервера ни на что не влияет, а лишний
  // запрос в момент установки приложения — лишний повод ей не состояться.
  if (!lockAppliesTo(pathname)) {
    resolved.value = true
    return
  }
  const schedule = await readLockSchedule()
  usePaymentLockHardFrom().value = schedule.hardFrom
  usePaymentLockStage().value = lockStageFor(new Date(), schedule, lockParam)
  resolved.value = true
}

export interface PaymentLockState {
  /**
   * Решение принято — до этого момента страницу монтировать нельзя.
   *
   * ⚠ Для страниц ВНЕ блокировки (`/`, `/install`) истинно сразу, ещё на пререндере: иначе в
   * статику запеклась бы пустая публичная страница.
   */
  resolved: Readonly<Ref<boolean>>
  /** Стадия блокировки: `none`, `soft` (экран с отсчётом) или `hard` (экран навсегда). */
  stage: Readonly<Ref<PaymentLockStage>>
  /** Экран держит страницу прямо сейчас. */
  blocking: ComputedRef<boolean>
  /** Сколько секунд осталось до снятия мягкой блокировки. */
  remaining: Readonly<Ref<number>>
  /**
   * День, с которого приложение перестанет открываться (`YYYY-MM-DD`), если он задан.
   *
   * ⚠ Экран напоминания обязан называть срок. «Подпишите акты» без даты читается как вежливая
   * формальность; «с 21.09 приложение открываться не будет» — как срок, у которого есть
   * последствие. Ради одной этой строки день и доезжает до экрана.
   */
  hardFrom: Readonly<Ref<string | undefined>>
}

/**
 * Состояние блокировки для экрана.
 *
 * ⚠ Зовётся ОДИН раз, из `app/app.vue`. Это важно не для экономии: отсидев двадцать секунд один
 * раз, человек не встречает экран снова на каждом переходе между отчётами. А открыв отчёт заново
 * из меню портала — встречает: там фрейм создаётся с нуля, и это тот самый случай, ради которого
 * напоминание и заведено.
 */
export function usePaymentLock(path: string): PaymentLockState {
  const stage = usePaymentLockStage()
  const hardFrom = usePaymentLockHardFrom()
  const released = usePaymentLockReleased()
  const resolved = usePaymentLockResolved()
  const remaining = ref(LOCK_RELEASE_SECONDS)
  const blocking = computed(() => stage.value !== 'none' && !released.value)

  // ⚠ Для страниц вне блокировки решение известно СРАЗУ и синхронно — в том числе на пререндере.
  // Без этой строки в статику запеклась бы пустая публичная страница и пустой установщик.
  if (!lockAppliesTo(path)) resolved.value = true

  let timer: ReturnType<typeof setInterval> | undefined
  // ⚠ Регистрируется СИНХРОННО, в setup. Внутри асинхронного хука `onScopeDispose` вызвался бы уже
  // после первого `await`, когда активной области видимости эффектов нет, и не зацепился бы ни за
  // что — таймер остался бы тикать в размонтированном экземпляре.
  onScopeDispose(() => clearInterval(timer))

  // ⚠ Отсчёт заводится ПО ПОЯВЛЕНИЮ мягкой стадии, а не по монтированию: стадия приезжает с
  // сервера, то есть позже. Наблюдатель, а не `onMounted`, — потому что момент известен только ему.
  watch(stage, (value) => {
    if (value !== 'soft' || timer) return
    // ⚠ Отсчёт ведётся от МОМЕНТА окончания, а не вычитанием по единице на такт. Вкладка в фоне
    // получает такты реже обещанного, и счётчик-вычитатель показывал бы «осталось 14» через минуту
    // после открытия. Здесь же экран просто догоняет реальное время.
    const deadline = Date.now() + LOCK_RELEASE_SECONDS * 1000
    timer = setInterval(() => {
      remaining.value = Math.max(0, Math.ceil((deadline - Date.now()) / 1000))
      if (remaining.value > 0) return
      clearInterval(timer)
      released.value = true
    }, TICK_MS)
  }, { immediate: true })

  return { resolved, stage, blocking, remaining, hardFrom }
}
