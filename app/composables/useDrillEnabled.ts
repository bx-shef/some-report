import type { ComputedRef, InjectionKey } from 'vue'

/**
 * Можно ли открывать детализацию — то есть кликабельны ли числа отчёта.
 *
 * ⚠ Ответ знает СТРАНИЦА, а не компонент. Список открывает настоящий слайдер Битрикс24, а он
 * существует только внутри портала; вне фрейма (`?preview=1`) детализации нет совсем — решение
 * владельца от 2026-09-06. Но спрашивать про это SDK прямо из таблицы значило бы завести в
 * рисующем компоненте знание о портале, а по устройству проекта компоненты только рисуют.
 *
 * ⚠ Умолчание — `true`, и это не лень. Компонент, вставленный без страницы (а так его и монтируют
 * тесты вёрстки), обязан рисовать ПОЛНЫЙ вид со всеми кнопками: иначе тест «клик по числу»
 * молча проверял бы экран без кнопок и был бы зелёным всегда.
 */
const DRILL_ENABLED = Symbol('drill-enabled') as InjectionKey<ComputedRef<boolean>>

/** Страница объявляет, работает ли детализация. Звать в `setup` страницы отчёта. */
export function provideDrillEnabled(value: ComputedRef<boolean>): void {
  provide(DRILL_ENABLED, value)
}

/** Кликабельны ли числа. Вне страницы отчёта — да (см. шапку). */
export function useDrillEnabled(): ComputedRef<boolean> {
  return inject(DRILL_ENABLED, computed(() => true))
}
