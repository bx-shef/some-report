/**
 * Единый список маршрутов приложения. Отсюда `nuxt.config.ts` берёт список пререндера, а шапка
 * отчётов — переключатель между ними.
 *
 * ⚠ Держать копию списка в конфиге нельзя: страницы приложения не связаны ссылками с публичной
 * страницей, краулер `nuxt generate` их не находит, и забытый маршрут превращается в 404 ровно
 * в портале — там, где его никто не проверяет до установки клиенту.
 */

/** Публичная страница — единственная, которую имеет смысл индексировать. */
export const PUBLIC_ROUTES = ['/'] as const

/**
 * Главная страница приложения: выбор отчёта. Её открывает плитка приложения в «Приложениях».
 *
 * ⚠ Пункты CRM-аналитики ведут НЕ сюда, а прямо в отчёты (`app/config/b24.ts`, `PLACEMENTS`) —
 * решение владельца от 2026-09-05. Пути отчётов менять нельзя, не перерегистрировав плейсменты
 * на всех установленных порталах.
 */
export const APP_HOME = '/app'

/** Отчёты приложения: путь, название и одна строка о том, на какой вопрос отчёт отвечает. */
export const APP_REPORTS = [
  {
    path: '/app/leads',
    title: 'Аналитика по лидам',
    summary: 'Путь лида от поступления до закрытия сделки: воронка, брак лидов с причинами, причины проигрыша сделок, эффективность источников.'
  },
  {
    path: '/app/managers',
    title: 'Сделки по менеджерам',
    summary: 'Сколько сделок у каждого менеджера в каждой «моей компании» и на какой они стадии: кольцевая диаграмма распределения и таблица. Направление, охват, компания и период — фильтром.'
  }
] as const

/**
 * Служебные страницы: осмысленны только внутри фрейма Битрикс24.
 * - `/app` — главная приложения, выбор отчёта (её открывает плитка приложения);
 * - `/app/leads`, `/app/managers` — сами отчёты, их открывают пункты CRM-аналитики;
 * - `/install` — обработчик установки приложения (регистрирует плейсменты, зовёт `installFinish`).
 */
export const SERVICE_ROUTES = [APP_HOME, ...APP_REPORTS.map(report => report.path), '/install'] as const

/**
 * Пути, которые ПОРТАЛ открывает сам, POST-запросом: обработчики плейсментов и установщик.
 *
 * ⚠ С 2026-09-05 сюда входят и САМИ ОТЧЁТЫ: пункты CRM-аналитики ведут прямо в них, то есть
 * портал POST-ит на `/app/leads` и `/app/managers`. Список нужен смоуку — статике POST не
 * положен, и без `error_page 405 =200` в nginx портал показывал бы пустой виджет при совершенно
 * исправной сборке. Забыть отчёт в этом списке значит узнать о 405 от клиента.
 *
 * ⚠ Сегодня список совпадает с `SERVICE_ROUTES`, и это совпадение, а не одно и то же: там —
 * «страницы не для публики», здесь — «сюда портал стучится POST-ом». Разъедутся они на первой же
 * странице приложения, на которую портал не ходит сам.
 */
export const PORTAL_HANDLER_ROUTES = [APP_HOME, ...APP_REPORTS.map(report => report.path), '/install'] as const

/** Что обязано оказаться в статике после `nuxt generate`. */
export const PRERENDER_ROUTES: string[] = [...PUBLIC_ROUTES, ...SERVICE_ROUTES]
