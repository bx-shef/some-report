/**
 * Единый список маршрутов приложения. Отсюда `nuxt.config.ts` берёт список пререндера, а шапка
 * отчётов — переключатель между ними.
 *
 * ⚠ Держать копию списка в конфиге нельзя: страницы приложения не связаны ссылками с публичной
 * страницей, краулер `nuxt generate` их не находит, и забытый маршрут превращается в 404 ровно
 * в портале — там, где его никто не проверяет до установки клиенту.
 */

/** Публичная страница — единственная, которую имеет смысл индексировать. */
export const PUBLIC_ROUTES = ['/'] as const

/**
 * Главная страница приложения: выбор отчёта. Её же открывает портал по пункту меню
 * (`PLACEMENT_HANDLER_PATH`), поэтому путь менять нельзя, не перерегистрировав плейсменты на всех
 * установленных порталах.
 */
export const APP_HOME = '/app'

/** Отчёты приложения: путь, название и одна строка о том, на какой вопрос отчёт отвечает. */
export const APP_REPORTS = [
  {
    path: '/app/leads',
    title: 'Аналитика по лидам',
    summary: 'Путь лида от поступления до закрытия сделки: воронка, брак лидов с причинами, причины проигрыша сделок, эффективность источников.'
  },
  {
    path: '/app/managers',
    title: 'Сделки по менеджерам',
    summary: 'Сколько сделок у каждого менеджера в каждом офисе («моя компания» сделки) и на какой они стадии. Направление выбирается фильтром.'
  }
] as const

/**
 * Служебные страницы: осмысленны только внутри фрейма Битрикс24.
 * - `/app` — главная приложения, выбор отчёта (её открывает пункт CRM-аналитики);
 * - `/app/leads`, `/app/managers` — сами отчёты;
 * - `/install` — обработчик установки приложения (регистрирует плейсменты, зовёт `installFinish`).
 */
export const SERVICE_ROUTES = [APP_HOME, ...APP_REPORTS.map(report => report.path), '/install'] as const

/**
 * Пути, которые ПОРТАЛ открывает сам, POST-запросом: обработчик плейсмента и установщик.
 *
 * ⚠ Отчёты сюда не входят: на них человек переходит уже внутри приложения, обычной ссылкой.
 * Список нужен смоуку — статике POST не положен, и без `error_page 405 =200` в nginx портал
 * показывал бы пустой виджет при совершенно исправной сборке.
 */
export const PORTAL_HANDLER_ROUTES = [APP_HOME, '/install'] as const

/** Что обязано оказаться в статике после `nuxt generate`. */
export const PRERENDER_ROUTES: string[] = [...PUBLIC_ROUTES, ...SERVICE_ROUTES]
