/**
 * Абсолютный URL обработчика плейсмента.
 *
 * ⚠ Именно АБСОЛЮТНЫЙ: относительный путь `placement.bind` не примет, а пустой `siteUrl` дал бы
 * зарегистрированный плейсмент, который открывает пустоту, — и заметно это стало бы только у
 * клиента. Поэтому пустой адрес возвращает `null`, а страница установки показывает ошибку.
 */
export function placementHandlerUrl(siteUrl: string): string | null {
  const base = siteUrl.trim().replace(/\/+$/, '')
  if (!base || !/^https:\/\//i.test(base)) return null
  return `${base}${PLACEMENT_HANDLER_PATH}`
}
