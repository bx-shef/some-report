import type { ReportPeriod } from '~/types/report'

/**
 * Типы отчёта «Активность пользователей»: сколько каждый сотрудник за период звонил, сколько
 * наговорил и сколько сделал дел в CRM.
 *
 * Слои те же, что у остальных отчётов: ВХОД — сырые записи и счётчики портала, ВЫХОД —
 * посчитанная таблица (`ActivityReport`). Ядро (`app/utils/activityLoad.ts`) не знает ни про REST,
 * ни про Vue, поэтому проверяется тестом целиком.
 *
 * ⚠ Отчёт перенесён с прежнего компонента заказчика (`reports.useractivity`), и его правила
 * СОХРАНЕНЫ, а не придуманы заново: считаются только состоявшиеся разговоры дольше порога.
 * Порог — настройка отчёта (решение владельца 2026-09-06), но умолчание то же, что было в коде
 * заказчика: `DEFAULT_CALL_THRESHOLD_SECONDS`.
 *
 * ⚠ Прежний отчёт считал ОДИН отдел (`DEPARTMENT = 62` было зашито в коде). Здесь отдела в
 * структуре нет вовсе: отчёт идёт по всем сотрудникам, а отдел выбирается фильтром (решение
 * владельца 2026-09-06).
 *
 * ⚠ Три блока прежнего отчёта сюда НЕ перенесены, и это решение замера, а не забывчивость
 * ([`docs/PORTAL.md`](../../docs/PORTAL.md), «Дела CRM, лиды и счета отчёта 3»): «дела без
 * крайнего срока» (у `crm.activity.list` нет фильтра «поле пусто» — все три написания отвечают
 * нулём при непустом портале), «счета» (`crm.invoice.list` отдаёт ноль: заказчик перешёл на
 * смарт-процессы) и группировка дел по `PROVIDER_ID` (13 781 дело из 36 571 создано обменом с 1С,
 * и строка «1CTOTAL» встала бы рядом со встречами менеджера).
 */

/**
 * Направление звонка.
 *
 * ⛔ Портал кодирует его полем `CALL_TYPE`, и значения ОБРАТНЫ наивному чтению: `1` — ИСХОДЯЩИЙ,
 * `2` — ВХОДЯЩИЙ. Имя фильтра (`INCOMING`) толкает прочитать наоборот, документация значения не
 * расшифровывает вовсе. Проверено на живом портале поимённо, на 38 звонках через связанные дела
 * CRM ([`docs/PORTAL.md`](../../docs/PORTAL.md), «Телефония»). Перепутать здесь — поменять
 * местами два столбца отчёта, и по числам это НЕ ВИДНО: оба варианта правдоподобны.
 */
export type CallDirection = 'in' | 'out'

/** Сырая запись звонка, как её отдаёт `voximplant.statistic.get`. Поля — только нужные отчёту. */
export interface B24CallRow {
  PORTAL_USER_ID?: string | number
  /** `1` — исходящий, `2` — входящий. См. `CallDirection`. */
  CALL_TYPE?: string | number
  /** Секунды разговора. Строкой — портал отдаёт числа строками. */
  CALL_DURATION?: string | number
  /** `200` — состоявшийся разговор; остальное — недозвон, отказ, сброс. */
  CALL_FAILED_CODE?: string | number
  CALL_START_DATE?: string
}

/** Звонки одного направления: сколько их и сколько наговорили. */
export interface CallTally {
  count: number
  /**
   * Суммарная длительность в СЕКУНДАХ.
   *
   * ⚠ В секундах, а не в минутах, потому что складывать надо сырые значения портала: округли
   * каждый звонок до минут — и сумма сотни коротких разговоров уедет на десятки минут. В минуты
   * переводит только показ (`formatDuration`).
   */
  seconds: number
}

/**
 * Звонки одного сотрудника — всё, что даёт телефония.
 *
 * ⚠ Отдельный тип, а не поля строки, потому что звонки приезжают ОТДЕЛЬНЫМ проходом и позже
 * остального: месяц — это 209 страниц по 50 записей, ≈ 1,5 минуты даже параллельно
 * ([`docs/PORTAL.md`](../../docs/PORTAL.md), «Длительность разговоров»). Пока их нет, таблица
 * уже показывает дела и лиды.
 */
export interface CallStats {
  /** Разговоры, попавшие под правило: состоявшиеся и дольше порога. */
  calls: Record<CallDirection, CallTally>
  /**
   * Звонки, НЕ ставшие разговором: недозвон, отказ, сброс.
   *
   * ⚠ Считаются отдельно и в длительность не входят. У заказчика это самостоятельный показатель:
   * «звонил, но не поговорил» — не то же самое, что «не звонил».
   */
  failed: number
  /** Разговоры короче порога: дозвонился, но разговора не вышло. */
  tooShort: number
}

/**
 * Вид дела CRM, который считает отчёт.
 *
 * ⛔ Звонка здесь НЕТ намеренно. Дела `VOXIMPLANT_CALL` — это те же самые звонки, что отдаёт
 * телефония (август: 18 418 и там, и там), только без длительности. Посчитай отчёт и то, и
 * другое — одни и те же разговоры встали бы в таблицу дважды, под разными числами, потому что у
 * дел нет ни порога, ни кода завершения.
 */
export type DeedKind = 'email' | 'meeting' | 'task'

/** Дела CRM одного сотрудника за период. */
export interface DeedCounts {
  /**
   * Письма по направлению — у них оно есть и осмысленно: за август у заказчика 2 995 ВХОДЯЩИХ
   * (`DIRECTION: 1`) против 1 343 исходящих (`DIRECTION: 2`).
   *
   * ⛔ Не перепутайте со звонками: у телефонии шкала ОБРАТНАЯ (`CALL_TYPE: 1` — исходящий).
   * Перевод между ними живёт в `activityQuery.ts` (`DEED_DIRECTION`) и закрыт тестом.
   */
  email: Record<CallDirection, number>
  /**
   * Встречи.
   *
   * ⚠ Одним числом, а не по направлениям: портал ставит встрече `DIRECTION: 0` — проверено, все
   * 34 встречи августа. Столбцы «входящие встречи» и «исходящие встречи» были бы вечными нулями.
   */
  meeting: number
  /** Задачи CRM. */
  task: number
  /**
   * Не выполненные дела, срок которых истёк к концу периода, — «висяки».
   *
   * ⚠ Это единственный показатель отчёта, который считается НЕ ЗА ПЕРИОД, а НА КОНЕЦ периода:
   * условие прежнего отчёта — `COMPLETED: 'N'` и `END_TIME` не позже конца периода, без нижней
   * границы. Просроченное дело трёхлетней давности — тоже висяк.
   */
  overdue: number
}

/** Лиды сотрудника за период. */
export interface LeadCounts {
  /** Создано в периоде (`DATE_CREATE`). */
  created: number
  /**
   * Закрыто успешно в периоде.
   *
   * ⚠ По дате ЗАКРЫТИЯ (`DATE_CLOSED`), а не создания: закрытый в августе лид мог прийти в мае, и
   * это работа августа. Поэтому `created` и `won + lost` в одной строке НЕ обязаны сходиться —
   * это разные вопросы, а не расхождение.
   */
  won: number
  /** Закрыто провалом в периоде — та же дата закрытия. */
  lost: number
}

/**
 * Отдел портала. `parentId` пуст у корня.
 *
 * ⚠ Отделы — ДЕРЕВО, а не список: у заказчика 43 отдела, из них 11 с подотделами, и люди сидят
 * и в узлах, и в листьях ([`docs/PORTAL.md`](../../docs/PORTAL.md), «Отделы»).
 */
export interface DepartmentRef {
  id: number
  name: string
  parentId?: number
  sort?: number
}

/** Сотрудник, которого отчёт показывает строкой. */
export interface ActivityUser {
  id: number
  name: string
  /** Уволен — портал отдал его вторым проходом `user.get` с `ACTIVE: false`. */
  dismissed?: boolean
  /** Отделы сотрудника (`UF_DEPARTMENT`): по ним работает фильтр. */
  departmentIds?: readonly number[]
}

/** Строка отчёта: один сотрудник. */
export interface ActivityRow extends CallStats {
  userId: number
  userName: string
  /** Сотрудник уволен — портал отдал его с `ACTIVE: false`. См. `ManagerRef.dismissed`. */
  dismissed?: boolean
  deeds: DeedCounts
  leads: LeadCounts
  /**
   * Дела и лиды у этой строки СПРАШИВАЛИ.
   *
   * ⚠ Нужен потому, что звонки приезжают вторым проходом и приносят сотрудников, которых в списке
   * не было (звонок без `PORTAL_USER_ID`, сотрудник вне выбранного отдела). Счётчики дел им никто
   * не задавал — и напечатать им «0 писем» значило бы соврать: ноль здесь означал бы «не
   * спрашивали», а читался бы как «не писал». Экран в такой строке ставит прочерк.
   */
  deedsKnown: boolean
}

/** Итоги отчёта — считаются ядром, а не суммируются на экране. */
export interface ActivityTotals extends CallStats {
  deeds: DeedCounts
  leads: LeadCounts
  /** Сотрудников хотя бы с одним действием. */
  users: number
}

/** Готовая таблица отчёта. */
export interface ActivityReport {
  rows: ActivityRow[]
  /**
   * Итог ПО ПОКАЗАННЫМ СТРОКАМ, а не по порталу.
   *
   * ⚠ Здесь, в отличие от отчёта по менеджерам, отдельного счётчика «всего по порталу» нет и
   * остатка «вне строк» тоже. И это не забытая проверка: строки отчёта 2 ВЫВОДЯТСЯ из сделок, и
   * ответственный мог не попасть в перечисление, а здесь строки — это сам список сотрудников из
   * `user.get`, и фильтр по отделу сужает его НАМЕРЕННО. Итог портала под таким фильтром всегда
   * отличался бы от суммы строк, ничего при этом не означая.
   */
  totals: ActivityTotals
  /** Порог, которым считали: экран обязан назвать его, иначе числа не с чем сверить. */
  thresholdSeconds: number
  /** Звонки уже приехали. Пока `false` — их столбцы пусты не потому, что звонков не было. */
  callsKnown: boolean
}

/** Отбор отчёта: период обязателен, отдел — нет. */
export interface ActivityFilters {
  period: ReportPeriod
  /** Отдел (`UF_DEPARTMENT`). Не выбран — все сотрудники. */
  departmentId?: number
  /** Порог разговора в секундах — настройка отчёта. */
  thresholdSeconds: number
}

/**
 * Порог разговора по умолчанию — 29 секунд.
 *
 * ⚠ Это правило ЗАКАЗЧИКА, перенесённое из прежнего отчёта (`MIN_CALL_DURATION = 29` в
 * `reports.useractivity/class.php`), а не «разумное умолчание». Оно отсекает почти половину:
 * из 19 015 звонков августа под него попадают 10 404 ([`docs/PORTAL.md`](../../docs/PORTAL.md)).
 * Меняя умолчание, вы меняете все числа отчёта относительно тех, к которым заказчик привык.
 */
export const DEFAULT_CALL_THRESHOLD_SECONDS = 29

/** Код завершения состоявшегося разговора. Всё остальное — недозвон, отказ, сброс. */
export const CALL_SUCCESS_CODE = '200'
