/**
 * Типы отчёта «Активность пользователей»: сколько каждый сотрудник за период звонил, сколько
 * наговорил и сколько сделал дел в CRM.
 *
 * Слои те же, что у остальных отчётов: ВХОД — сырые записи и счётчики портала, ВЫХОД —
 * посчитанная таблица (`ActivityReport`). Ядро (`app/utils/activityLoad.ts`) не знает ни про REST,
 * ни про Vue, поэтому проверяется тестом целиком.
 *
 * ⚠ Отчёт перенесён с прежнего компонента заказчика (`reports.useractivity`), и его правила
 * СОХРАНЕНЫ, а не придуманы заново: считаются только состоявшиеся разговоры дольше порога.
 * Порог — настройка отчёта (решение владельца 2026-09-06), но умолчание то же, что было в коде
 * заказчика: `DEFAULT_CALL_THRESHOLD_SECONDS`.
 *
 * ⚠ Прежний отчёт считал ОДИН отдел (`DEPARTMENT = 62` было зашито в коде). Здесь отдела в
 * структуре нет вовсе: отчёт идёт по всем сотрудникам, а отдел выбирается фильтром (решение
 * владельца 2026-09-06).
 */

/**
 * Направление звонка.
 *
 * ⛔ Портал кодирует его полем `CALL_TYPE`, и значения ОБРАТНЫ наивному чтению: `1` — ИСХОДЯЩИЙ,
 * `2` — ВХОДЯЩИЙ. Имя фильтра (`INCOMING`) толкает прочитать наоборот, документация значения не
 * расшифровывает вовсе. Проверено на живом портале через связанные дела CRM
 * ([`docs/PORTAL.md`](../../docs/PORTAL.md), «Телефония»). Перепутать здесь — поменять местами два
 * столбца отчёта, и по числам это НЕ ВИДНО: оба варианта правдоподобны.
 */
export type CallDirection = 'in' | 'out'

/** Сырая запись звонка, как её отдаёт `voximplant.statistic.get`. Поля — только нужные отчёту. */
export interface B24CallRow {
  PORTAL_USER_ID?: string | number
  /** `1` — исходящий, `2` — входящий. См. `CallDirection`. */
  CALL_TYPE?: string | number
  /** Секунды разговора. Строкой — портал отдаёт числа строками. */
  CALL_DURATION?: string | number
  /** `200` — состоявшийся разговор; остальное — недозвон, отказ, сброс. */
  CALL_FAILED_CODE?: string | number
  CALL_START_DATE?: string
}

/** Звонки одного направления: сколько их и сколько наговорили. */
export interface CallTally {
  count: number
  /**
   * Суммарная длительность в СЕКУНДАХ.
   *
   * ⚠ В секундах, а не в минутах, потому что складывать надо сырые значения портала: округли
   * каждый звонок до минут — и сумма сотни коротких разговоров уедет на десятки минут. В минуты
   * переводит только показ (`formatDuration`).
   */
  seconds: number
}

/** Строка отчёта: один сотрудник. */
export interface ActivityRow {
  userId: number
  userName: string
  /** Сотрудник уволен — портал отдал его с `ACTIVE: false`. См. `ManagerRef.dismissed`. */
  dismissed?: boolean
  /** Разговоры, попавшие под правило: состоявшиеся и дольше порога. */
  calls: Record<CallDirection, CallTally>
  /**
   * Звонки, НЕ ставшие разговором: недозвон, отказ, сброс.
   *
   * ⚠ Считаются отдельно и в длительность не входят. У заказчика это самостоятельный показатель:
   * «звонил, но не поговорил» — не то же самое, что «не звонил».
   */
  failed: number
  /** Разговоры короче порога: дозвонился, но разговора не вышло. */
  tooShort: number
}

/** Итоги отчёта — считаются ядром, а не суммируются на экране. */
export interface ActivityTotals {
  calls: Record<CallDirection, CallTally>
  failed: number
  tooShort: number
  /** Сотрудников со звонками хотя бы одного вида. */
  users: number
}

/** Готовая таблица отчёта. */
export interface ActivityReport {
  rows: ActivityRow[]
  totals: ActivityTotals
  /** Порог, которым считали: экран обязан назвать его, иначе числа не с чем сверить. */
  thresholdSeconds: number
}

/**
 * Порог разговора по умолчанию — 29 секунд.
 *
 * ⚠ Это правило ЗАКАЗЧИКА, перенесённое из прежнего отчёта (`MIN_CALL_DURATION = 29` в
 * `reports.useractivity/class.php`), а не «разумное умолчание». Оно отсекает почти половину:
 * из 19 015 звонков августа под него попадают 10 404 ([`docs/PORTAL.md`](../../docs/PORTAL.md)).
 * Меняя умолчание, вы меняете все числа отчёта относительно тех, к которым заказчик привык.
 */
export const DEFAULT_CALL_THRESHOLD_SECONDS = 29

/** Код завершения состоявшегося разговора. Всё остальное — недозвон, отказ, сброс. */
export const CALL_SUCCESS_CODE = '200'
