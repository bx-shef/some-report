import type { ReportPeriod } from '~/types/report'

/**
 * Типы отчёта «Сделки по менеджерам»: сколько сделок у каждого менеджера в каждом офисе и на
 * какой стадии.
 *
 * Слои те же, что у отчёта по лидам: ВХОД — счётчики портала и справочники (`ManagerLoadInput`),
 * ВЫХОД — посчитанная матрица (`ManagerLoadReport`). Ядро (`app/utils/managerLoad.ts`) не знает
 * ни про REST, ни про Vue: матрица собирается чистой функцией и потому проверяется тестом.
 *
 * ⚠ «Офис» здесь — поле сделки «Моя компания» (`MYCOMPANY_ID`), а не компания-клиент
 * (`COMPANY_ID`). Так его называет заказчик, и так же его называл прежний отчёт по заказам.
 */

/** Офис — значение «Моей компании» сделки. `id = 0` — поле не заполнено (`OFFICE_UNSET`). */
export interface OfficeRef {
  id: number
  name: string
}

/** Менеджер — ответственный за сделку (`ASSIGNED_BY_ID`). */
export interface ManagerRef {
  id: number
  name: string
}

/** Стадия направления: код, имя и семантика из справочника портала. */
export interface StageRef {
  id: string
  name: string
  /** `S` — успех, `F` — провал, `P` — в работе. Берётся из `crm.status.list`, не из кода стадии. */
  semantic: 'P' | 'S' | 'F'
}

/**
 * Какие сделки считаем.
 *
 * ⚠ Умолчание — `in-work`, и это не произвол: вопрос «сколько сделок на менеджере» — про
 * ТЕКУЩУЮ загрузку. Закрытых сделок на боевом портале 683 тысячи против 15 тысяч открытых, и с
 * ними матрица показывала бы историю за все годы вместо сегодняшней работы.
 */
export type DealScope = 'in-work' | 'won' | 'lost' | 'all'

/** Отбор отчёта: направление, охват и (необязательно) период создания сделки. */
export interface ManagerFilters {
  /** Направление сделок (`CATEGORY_ID`). Одно: у разных направлений стадии разные. */
  categoryId: number
  scope: DealScope
  /** Период по дате создания сделки. Пусто — за всё время (умолчание: загрузка «сейчас»). */
  period?: ReportPeriod
}

/** Строка матрицы: менеджер внутри офиса. */
export interface ManagerLoadRow {
  managerId: number
  managerName: string
  /** Код стадии → сколько сделок. Стадии без сделок в объект не попадают. */
  byStage: Record<string, number>
  /**
   * Сделки на стадиях, которых нет в справочнике направления (стадию удалили, сделки остались),
   * — остаток: итог счётчика минус сумма по колонкам. Число без списка, и потому некликабельное.
   */
  otherStages: number
  /** Итог по паре «офис + менеджер» — отдельный счётчик портала, а не сумма колонок. */
  total: number
  /** Доля от итога офиса, 0…1 — для полосы в таблице. */
  share: number
}

/** Группа матрицы: один офис со своими менеджерами. */
export interface ManagerLoadOffice {
  officeId: number
  officeName: string
  /** Менеджеры по убыванию числа сделок. */
  rows: ManagerLoadRow[]
  byStage: Record<string, number>
  otherStages: number
  total: number
  /**
   * Сделки офиса, не попавшие ни в одну строку: ответственный не назначен, уволен и не найден
   * перечислением или сделку создали между двумя пакетами счётчиков. Остаток арифметики.
   */
  unlisted: number
  /**
   * Как эти сделки разложены по стадиям: итог колонки (счётчик портала) минус сумма клеток над
   * ним. Стадия у них известна, ответственный — нет, поэтому строка есть, а список за числом
   * собрать нечем: «ответственный не тот» фильтром REST не выразить.
   */
  unlistedByStage: Record<string, number>
  /** Доля офиса от общего итога, 0…1. */
  share: number
}

/** Посчитанный отчёт. */
export interface ManagerLoadReport {
  /** Офисы по убыванию числа сделок; «Моя компания не указана» — всегда последней. */
  offices: ManagerLoadOffice[]
  /** Колонки таблицы: стадии охвата, у которых есть хоть одна сделка. */
  stages: StageRef[]
  /** Сколько стадий охвата скрыто как пустые — подписью под таблицей, а не молча. */
  hiddenStages: number
  byStage: Record<string, number>
  otherStages: number
  unlisted: number
  /** Всего сделок под отбором — счётчик портала. */
  total: number
  /** Сколько менеджеров хотя бы с одной сделкой. */
  managers: number
  /** Сколько офисов с хотя бы одной сделкой (вместе с «не указана»). */
  officeCount: number
}

/** Направление сделок (`CATEGORY_ID`) — то, что в интерфейсе портала называется «воронка». */
export interface CategoryRef {
  id: number
  name: string
}

/**
 * Число матрицы, по которому нажали: за ним открывается список сделок ТЕМ ЖЕ условием.
 * Пусто в `managerId` — итог офиса, пусто в `stageId` — итог строки.
 */
export interface ManagerCellRef {
  officeId: number
  managerId?: number
  stageId?: string
  /** Как подписано число на экране — оно же станет заголовком списка. */
  title: string
  /** Само число — чтобы список сказал «показано M из N», не долистывая до конца. */
  total: number
}
