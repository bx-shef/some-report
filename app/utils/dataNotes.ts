import type { ManagerLoadReport } from '~/types/managers'
import type { AdapterWarnings } from '~/utils/b24Adapter'
import { formatCount } from '~/utils/format'

/**
 * Оговорки к качеству данных портала для отчёта «Аналитика по лидам».
 *
 * ⚠ Молчать о них нельзя. «Сделок, не связанных с лидом: 340» — это объяснение, почему воронка
 * показывает ноль квалифицированных; без него руководитель читает ноль как факт о работе отдела
 * продаж. Каждая строка здесь — не про наш код, а про то, что нужно поправить в CRM.
 *
 * ⚠ Функция вынесена со страницы намеренно: это чистое преобразование, и в компоненте текст,
 * который человек читает вместо цифры, оставался бы без единого теста — а именно он и решает,
 * пойдёт ли кто-то чинить данные.
 *
 * ⚠ Числа печатаются через `formatCount`, а не интерполяцией: то же число рядом, в блоке 7,
 * идёт через него же, и «4997» против «4 997» под одной цифрой читается как две разных.
 *
 * ⛔ Здесь ровно те оговорки, которые ЖИВАЯ выборка умеет выставить. Три бывших («лид вне
 * периода», «успех без сделки», «время первого ответа не выбиралось») ушли вместе с цельным
 * разбором строками: связи лид → сделка счётчики не видят поимённо, а про время первого ответа
 * блок 6 говорит сам. Хранить текст, который никогда не покажется, — это не запас, а ложное
 * обещание: его сопровождают, тестируют и учитывают при правках, а он мёртв.
 *
 * @param warnings оговорки адаптера; `undefined` — выборки ещё не было
 * @returns готовые строки в порядке показа; пустой массив — сказать нечего
 */
export function leadsDataNotes(w: AdapterWarnings | undefined): string[] {
  if (!w) return []
  const notes: string[] = []
  if (w.dealsWithoutLead > 0) {
    notes.push(`Сделок без связи с лидом среди выбранных строками: ${formatCount(w.dealsWithoutLead)} — в разрез источников лидов они не попадают.`)
  }
  /**
   * ⚠ Зовём проверить в CRM, а не просто сообщаем число. Замер боевого портала 2026-09-07: 403
   * сделки не в BYN (395 RUB, 7 USD, 1 EUR), курса ни у одной из этих валют в портале НЕТ, и
   * 162 успешных из них складываются в выручку как есть — 22 211 807 «условных», где рубли и
   * доллары посчитаны белорусскими рублями. Это не техническая оговорка, а испорченная цифра.
   *
   * ⚠ Счётчик считает сделки ЛЮБОГО исхода, а выручку делают только успешные — на боевом это
   * 403 против 162. Поэтому текст говорит «сложены с остальными», а не «вошли в выручку»: иначе
   * человек пойдёт искать в CRM расхождение в два с половиной раза больше настоящего.
   */
  if (w.unconvertedDeals > 0) {
    notes.push(`Сделок в валюте, которой нет в справочнике портала: ${formatCount(w.unconvertedDeals)} — их суммы сложены с остальными КАК ЕСТЬ, без пересчёта. Проверьте их в CRM: там, где такая сделка успешна, на эту разницу расходится выручка.`)
  }
  /**
   * ⚠ Отдельно от предыдущей строки, хотя обе про валюту. Там валюта НЕИЗВЕСТНА — это сломано, и
   * сумма взята как есть. Здесь всё сработало верно: курс нашёлся, сумму привели.
   *
   * Говорим всё равно, потому что у заказчика все сделки должны быть в базовой валюте: «Все
   * сделки в BYN. Судя по всему сделки в рублях это неправильные сделки» (2026-09-03). Значит
   * это ошибка ВВОДА, а приведённая курсом сделка неотличима в выручке от правильной — молча
   * сложив её, отчёт растворяет ошибку, и никто её больше не найдёт.
   */
  if (w.foreignCurrencyDeals > 0) {
    notes.push(`Сделок не в базовой валюте портала: ${formatCount(w.foreignCurrencyDeals)} — суммы приведены курсом, посчитаны они верно. Проверьте их в CRM: по договорённости все сделки заводятся в одной валюте.`)
  }
  if (w.duplicateIds > 0) {
    notes.push(`Повторов по идентификатору отброшено: ${formatCount(w.duplicateIds)}.`)
  }
  if (w.wonWithoutAmount > 0) {
    notes.push(`Успешных сделок из лидов с нулевой суммой: ${formatCount(w.wonWithoutAmount)}. Выручка по лидам считается по сумме сделки, а она в CRM не заполнена — деньги, судя по всему, оформляются на других сделках.`)
  }
  if (w.mergedLossReasons > 0) {
    notes.push(`Одинаковые причины проигрыша из разных направлений сведены в одну строку: стадий свёрнуто ${formatCount(w.mergedLossReasons)}. В CRM они по-прежнему разные.`)
  }
  return notes
}

/**
 * Оговорки к матрице отчёта «Сделки по менеджерам».
 *
 * ⚠ Здесь они особенно нужны: итог компании — ОТДЕЛЬНЫЙ счётчик портала, а не сумма строк
 * (счётчики приходят разными пакетами, между ними портал живёт). Разница обязана быть названа
 * остатком, а не спрятана: «сделок в таблице 25, а всего 30» без объяснения читается как
 * потерянные отчётом данные.
 *
 * ⚠ Причины усечения РАЗНЫЕ, и подсказка человеку тоже разная. Общий флаг «что-то не поместилось»
 * назвал бы неверную причину, а по ней и действие: сузить отбор направлением — не то же самое,
 * что сузить его периодом.
 *
 * @param report посчитанный отчёт
 * @param truncated что именно не поместилось в один проход перечисления
 * @returns готовые строки в порядке показа; пустой массив — сказать нечего
 */
export function managerDataNotes(
  report: ManagerLoadReport,
  truncated: { managers: boolean, companies: boolean }
): string[] {
  const notes: string[] = []
  if (report.unlisted > 0) {
    /**
     * ⚠ Причина здесь ОДНА: ответственный у сделки обязателен (замер 2026-09-05 — ни одной без
     * него из 689 523). Значит сделка выпала из строк только потому, что её сотрудник не попал в
     * перечисление; называть иную причину — уводить человека от настоящей.
     */
    notes.push(`Сделок вне строк таблицы: ${formatCount(report.unlisted)} — их ответственный не попал в перечисление: сделки появились уже после того, как отчёт перечислил менеджеров, или сотрудников больше, чем он перечисляет за проход.`)
  }
  if (report.otherStages > 0) {
    notes.push(`Сделок на стадиях, которых нет в справочнике направления: ${formatCount(report.otherStages)} — стадию удалили из воронки, а сделки на ней остались.`)
  }
  if (truncated.managers) {
    notes.push('Сотрудников в этом направлении больше, чем отчёт перечисляет за один проход: часть сделок ушла в строку «вне таблицы». Сузьте отбор — направлением, охватом или периодом.')
  }
  if (truncated.companies) {
    notes.push('«Моих компаний» у сделок больше, чем отчёт перечисляет за один проход: часть из них не попала даже в фильтр, и открыть их нечем. Сузьте отбор — направлением, охватом или периодом.')
  }
  if (report.hiddenStages > 0) {
    notes.push(`Пустых стадий скрыто: ${formatCount(report.hiddenStages)} — в них нет ни одной сделки под этим отбором.`)
  }
  return notes
}
