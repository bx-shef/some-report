/**
 * Параметры запроса к порталу — БЕЗ реактивных обёрток Vue.
 *
 * ⛔ Заведено по боевому инциденту 2026-09-14. Клик по причине проигрыша открывал слайдер с
 * верным заголовком и красной плашкой вместо списка:
 *
 * > Failed to execute 'structuredClone' on 'Window': [object Object] could not be cloned.
 *
 * Фрейм разговаривает с порталом через `postMessage`, а браузер клонирует полезную нагрузку
 * СТРУКТУРНЫМ клонированием. Оно умеет копировать обычные объекты и массивы — и НЕ умеет
 * копировать `Proxy`. Реактивность Vue — это ровно `Proxy`, поэтому любое значение, дошедшее до
 * запроса прямо из `ref`/`reactive`, роняет запрос целиком.
 *
 * ⚠ Ловушка в том, что видно это НЕ ВЕЗДЕ. Разворот объекта (`{ ...filter }`) снимает обёртку с
 * верхнего уровня, и пока значения фильтра — строки и числа, всё работает годами. Первый же
 * МАССИВ внутри (коды стадий одной причины провала, перечисление идентификаторов сделок)
 * приезжает `Proxy`-массивом, и список перестаёт открываться. То есть дефект ждёт не любого
 * клика, а клика по числу, за которым стоит перечисление, — и выглядит как поломка портала.
 *
 * ⚠ Лечится ГЛУБОКОЙ копией, а не `toRaw`: `toRaw` разворачивает только верхний уровень, ровно
 * как спред, и на вложенном массиве даёт тот же отказ.
 *
 * ⚠ Через JSON, а не через `structuredClone`, и это не лень. Во-первых, `structuredClone` сам по
 * себе споткнулся бы о `Proxy` — то есть о ту самую задачу, которую решаем. Во-вторых, JSON здесь
 * не теряет ничего: в параметрах портала живут строки, числа, `null` (значимое условие «поле
 * пусто»), массивы и плоские объекты — ни дат, ни `Map`, ни функций там нет и быть не может,
 * запрос всё равно уезжает JSON-транспортом.
 */

/**
 * Глубокая копия параметров запроса без реактивных обёрток.
 *
 * ⚠ Зовётся на ГРАНИЦЕ с SDK, у самого вызова, а не там, где фильтр собирается. Собирают его
 * чистые функции из нескольких кусков, и какой из кусков в этот раз приехал из `ref` — по месту
 * сборки не видно. Единственное место, где точно известно, что дальше значение уходит в
 * `postMessage`, — сам вызов.
 *
 * ⚠ `undefined` в значениях JSON выбрасывает, и это здесь ПОЛЕЗНО: условие `{ STATUS_ID:
 * undefined }` портал видит как «поля нет», а не как «поле пусто», — то есть ровно так же, как
 * после этой копии.
 */
export function plainParams<T>(params: T): T {
  return JSON.parse(JSON.stringify(params)) as T
}
