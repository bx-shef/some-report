/**
 * Заголовок вкладки: имя страницы плюс имя приложения.
 *
 * Зачем отдельный модуль ради склейки двух строк: прежняя склейка жила прямо в `app.vue`, ничем
 * не проверялась и пережила появление ВТОРОГО и ТРЕТЬЕГО отчёта с именем первого в хвосте. Дефект
 * этого рода не видно там, где его ищут: внутри портала отчёт открыт во фрейме, и заголовок
 * вкладки принадлежит порталу, а не нам.
 */

import { APP_NAME, APP_NAME_FULL, APP_REPORTS } from '~/config/routes'

/** Путь отчёта — только из перечисленных, чтобы опечатку ловил компилятор, а не человек. */
export type ReportPath = (typeof APP_REPORTS)[number]['path']

/**
 * Заголовок вкладки для страницы.
 *
 * Без имени страницы (публичная страница) отдаём ПОЛНОЕ имя приложения: там уточнение «для
 * Битрикс24» — единственное место, где человек узнаёт, к какой системе это относится.
 */
export function pageTitle(title?: string): string {
  const own = title?.trim()
  return own ? `${own} — ${APP_NAME}` : APP_NAME_FULL
}

/**
 * Имя отчёта для заголовка вкладки — ТО ЖЕ, что стоит в пункте меню CRM-аналитики.
 *
 * ⚠ Не литерал на странице: у отчёта 1 заголовком было «Отчёт», и это читалось нормально ровно
 * пока отчёт был один. Две подписи одного отчёта — пункт меню и вкладка — расходятся молча, а
 * человек, открывший три отчёта в трёх вкладках, различает их только по этой строке.
 */
export function reportTitle(path: ReportPath): string {
  const report = APP_REPORTS.find(item => item.path === path)
  // ⚠ Тип не даёт промахнуться, но `find` этого не знает; падать здесь нельзя — заголовок вкладки
  // не повод не показать отчёт.
  return report?.title ?? APP_NAME
}
