/**
 * Отказы портала, которые отчёт обязан отличать друг от друга.
 *
 * ⚠ Отличать приходится по КОДУ, а не по тексту: текст портал отдаёт на языке портала и меняет
 * между версиями, а `AjaxError.code` — часть контракта REST.
 */

/**
 * Превышена интенсивность запросов (HTTP 503).
 *
 * Портал считает запросы «дырявым ведром»: на обычных тарифах 2 запроса в секунду при ведре в 50,
 * на «Энтерпрайзе» — 5 и 250. Отчёт легко выбирает ведро: месяц звонков отчёта 3 — восемь пакетов
 * подряд, а отчёт открывают несколько руководителей разом.
 *
 * ⚠ Это НЕ сбой сети и не ошибка данных: портал говорит «слишком часто, подожди». Сама платформа
 * рекомендует повторять с растущей задержкой — поэтому отказ по этому коду для нас не конец
 * выборки, а пауза.
 */
export const RATE_LIMIT_CODE = 'QUERY_LIMIT_EXCEEDED'

/**
 * Код ошибки портала, если он там есть.
 *
 * ⚠ Форму проверяем в рантайме: сюда приходит и `AjaxError` SDK (у него есть `code`), и обычный
 * `Error` (у него нет), и то, что вернул `getErrorsByKey()` пакета. Слепое приведение молча
 * объявило бы лимитом любую ошибку — и отчёт вечно ждал бы паузы вместо того, чтобы сказать
 * человеку правду.
 */
export function errorCode(error: unknown): string | undefined {
  if (typeof error !== 'object' || error === null) return undefined
  const code = (error as { code?: unknown }).code
  return typeof code === 'string' && code !== '' ? code : undefined
}

/** Отказ по интенсивности запросов — тот, который имеет смысл повторить после паузы. */
export function isRateLimit(error: unknown): boolean {
  return errorCode(error) === RATE_LIMIT_CODE
}

/**
 * Есть ли отказ по интенсивности среди ошибок пакета.
 *
 * ⚠ Пакет уходит с `isHaltOnError: false`, и SDK складывает ошибки КОМАНД во внешний результат
 * по их ключам (`getErrorsByKey`). Одна упёршаяся команда делает неуспешным весь пакет — значит
 * и повторять надо весь пакет, а не гадать, какая из полусотни команд не дошла.
 */
export function hasRateLimit(errors: Readonly<Record<string, unknown>>): boolean {
  return Object.values(errors).some(isRateLimit)
}

/**
 * Что сказать человеку, когда повторы не помогли.
 *
 * ⚠ «Не удалось прочитать данные портала» — неправда по существу: данные читаются, портал просто
 * просит реже. Человек, прочитавший правду, знает, что делать (подождать и открыть снова); тот,
 * кто прочитал «не удалось», идёт в поддержку.
 */
export const RATE_LIMIT_MESSAGE
  = 'Портал ограничил частоту запросов — слишком много обращений разом. Подождите минуту и откройте отчёт снова.'

/**
 * Пауза перед повтором со случайным разбросом.
 *
 * ⛔ Разброс — не украшение. Без него все, кто упёрся в лимит одновременно, повторят ровно через
 * секунду и ровно через три, то есть постучатся в портал в один и тот же момент. Отчёт общий: его
 * открывают несколько руководителей, да и один отчёт пускает несколько фоновых проходов сразу.
 * Документация портала прямо просит «не пускать параллельные серии с одного адреса» —
 * фиксированная пауза делает ровно это, только хором.
 *
 * ⚠ `random` параметром, а не `Math.random()` внутри: иначе разброс нельзя проверить, а
 * непроверяемая случайность — это случайность, которую однажды выключат и не заметят.
 */
export function retryDelayMs(baseMs: number, jitter: number, random: number): number {
  const spread = 1 + (random * 2 - 1) * jitter
  return Math.max(0, Math.round(baseMs * spread))
}
