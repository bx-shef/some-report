<script setup lang="ts">
import { formatCount } from '~/utils/format'

/**
 * Число клетки матрицы: кнопка со списком, если список за ним есть, иначе — текст или прочерк.
 *
 * ⚠ Отдельный компонент, потому что этих клеток на экране четыре ВИДА (строка менеджера, итог
 * менеджера, итог компании по стадии, итог компании), а с мобильной раскладкой стало восемь. Одна
 * и та же тройка ветвей, выписанная восемь раз, расходится молча: ревью уже находило, что в двух
 * копиях из четырёх ветка «число есть, но не кликабельно» была потеряна — вне портала там
 * пропадало само число.
 *
 * ⚠ Это НЕ `DrillNumber`: тому нужен готовый запрос списка, а его собирает страница отчёта 2 (она
 * знает отбор). Компонент отдаёт наружу только «по этой клетке нажали». Общий у них вид — класс
 * `.drill-number`, чтобы кликабельные числа обоих отчётов не разъехались.
 */
const props = defineProps<{
  /** Само число. `0` и `undefined` — клетка пустая. */
  value?: number
  /** Подсказка кнопки — то же, что окажется заголовком списка. */
  title: string
  /**
   * Показывать ли прочерк вместо пустого места.
   *
   * ⚠ У итогов он не нужен: там число есть всегда, а прочерк в колонке «Всего» читался бы как
   * «данные не пришли».
   */
  dash?: boolean
}>()
const emit = defineEmits<{ pick: [] }>()

/**
 * Числа кликабельны только внутри портала: список открывает настоящий слайдер Битрикс24, а вне
 * фрейма его нет (решение владельца от 2026-09-06). Кнопка, которая заведомо ничего не сделает,
 * читается как поломка отчёта. Ответ приходит от страницы — компонент про портал не знает.
 */
const drillEnabled = useDrillEnabled()
const has = computed(() => Boolean(props.value))
</script>

<template>
  <button
    v-if="has && drillEnabled"
    type="button"
    class="drill-number"
    :title="title"
    @click="emit('pick')"
  >
    {{ formatCount(value!) }}
  </button>
  <!-- ⚠ Вне портала ЧИСЛО остаётся, пропадает только ссылка: спрятать его значило бы соврать,
       что сделок нет. Прочерк — только у настоящего нуля. -->
  <span v-else-if="has">{{ formatCount(value!) }}</span>
  <span
    v-else-if="dash"
    class="opacity-30"
  >—</span>
</template>
