<script setup lang="ts">
import { formatCount } from '~/utils/format'

/**
 * Число таблицы отчёта «Активность пользователей»: кнопка со списком, число или прочерк.
 *
 * ⚠ Отдельный компонент по той же причине, что `ManagerCellNumber`: тринадцать столбцов в двух
 * раскладках дают под тридцать мест, где живёт одна и та же тройка ветвей. Выписанная тридцать
 * раз, она расходится молча — ревью отчёта 2 уже находило потерянную ветку в двух копиях из
 * четырёх.
 *
 * ⛔ Прочерк здесь значит НЕ ТО, что в отчёте 2. Там он у настоящего нуля, здесь — у «мы этого не
 * знаем»: звонки ещё читаются (полторы минуты) или дел этой строки отчёт не спрашивал вовсе
 * (сотрудник вне выбранного отдела). Настоящий ноль печатается нулём: «не звонил» и «не знаем,
 * звонил ли» — разные утверждения, и подменять одно другим нельзя.
 */
const props = defineProps<{
  /** Само число. Осмысленно только при `known`. */
  value: number
  /** Число ИЗВЕСТНО. `false` — прочерк: не прочитано или не спрашивалось. */
  known: boolean
  /** Подсказка кнопки — то же, что окажется заголовком списка. */
  title: string
  /**
   * За числом есть список ровно тем же условием.
   *
   * ⚠ Не «число больше нуля»: у длительности и у итогов списка нет по устройству отчёта
   * (`activityDrill.ts`), и решает это вызывающий, а не компонент.
   */
  drillable?: boolean
}>()
const emit = defineEmits<{ pick: [] }>()

/**
 * Числа кликабельны только внутри портала: список открывает настоящий слайдер Битрикс24, а вне
 * фрейма его нет (решение владельца от 2026-09-06). Кнопка, которая заведомо ничего не сделает,
 * читается как поломка отчёта.
 */
const drillEnabled = useDrillEnabled()
const clickable = computed(() => props.known && props.drillable && props.value > 0 && drillEnabled.value)
</script>

<template>
  <button
    v-if="clickable"
    type="button"
    class="drill-number"
    :title="title"
    @click="emit('pick')"
  >
    {{ formatCount(value) }}
  </button>
  <!-- ⚠ Вне портала ЧИСЛО остаётся, пропадает только ссылка: спрятать его значило бы соврать. -->
  <span v-else-if="known">{{ formatCount(value) }}</span>
  <span
    v-else
    class="opacity-30"
    title="Ещё не прочитано или не спрашивалось"
  >—</span>
</template>
